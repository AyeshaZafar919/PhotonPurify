import 'dart:io';
import 'package:ayesha_admin/Admin/screens/admin_home_page.dart';
import 'package:ayesha_admin/Client/client_home_page.dart';
import 'package:ayesha_admin/Technician/pages/technician_home_page.dart';
import 'package:ayesha_admin/login_page.dart';
import 'package:ayesha_admin/Admin/screens/home_page.dart';
import 'package:ayesha_admin/splash_screen.dart';
import 'package:flutter/material.dart';
import 'package:firebase_core/firebase_core.dart';
import 'Admin/screens/admin_dashboard.dart';
import 'firebase_options.dart'; // this file is generated by FlutterFire CLI


void main() async {
  WidgetsFlutterBinding.ensureInitialized();

  if (Firebase.apps.isEmpty) {
    if (Platform.isAndroid) {
      // ✅ Android auto-initializes Firebase
      await Firebase.initializeApp();
    } else {
      // ✅ iOS / Web need explicit options
      await Firebase.initializeApp(
        options: DefaultFirebaseOptions.currentPlatform,
      );
    }
  }

  runApp(const MyApp());
}

class MyApp extends StatelessWidget {
  const MyApp({super.key});

  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      debugShowCheckedModeBanner: false,
      title: 'Admin Panel',
      theme: ThemeData(
        primarySwatch: Colors.indigo,
        useMaterial3: true,
      ),
      initialRoute: '/',
      routes: {
        "/": (context) => const SplashScreen(),
        '/login': (context) => LoginPage(),
        '/dashboard': (context) => const AdminDashboard(),
        '/adminhome': (context) => const CeruleanThemePage(),
        '/techhome': (context) => const TechnicianHome(),
        //'/clienthome': (context) => const ClientHomePage(),
      },
      //home: LoginPage(),
    );
  }
}


